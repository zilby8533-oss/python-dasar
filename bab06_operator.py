# Operator aritmatika
a, b = 17, 5
print("a + b =", a + b)
print("a - b =", a - b)
print("a * b =", a * b)
print("a / b =", a / b)
print("a // b =", a // b)
print("a % b =", a % b)
print("a ** b =", a ** b)

# Operator assignment
x = 10
x += 5
x -= 3
x *= 2
x //= 4
print("x =", x)

# Operator perbandingan
print(a == b, a != b, a > b, a < b, a >= b, a <= b)

# Operator logika
lulus = True
hadir = False
print("and:", lulus and hadir)
print("or:", lulus or hadir)
print("not:", not lulus)
